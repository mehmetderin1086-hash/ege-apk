import 'common.dart';

typedef _PlateQuestion = ({
  BloomLevel bloom,
  AdvancedItem item,
  CreationTask? creation,
  MultiSelectTask? multiSelect,
});

_PlateQuestion _question(BloomLevel bloom, String prompt, String answer,
    List<String> distractors, String explanation,
    {CreationTask? creation, MultiSelectTask? multiSelect}) => (
      bloom: bloom,
      item: AdvancedItem(prompt, answer, distractors, explanation),
      creation: creation,
      multiSelect: multiSelect,
    );

List<AdvancedFamily> _plate(String id, String title, Topic topic,
    StudyLevel level, List<_PlateQuestion> questions) {
  final visual = QuestionVisual(kind: VisualKind.image, title: title, summary: '', imageID: id);
  return [
    for (final (index, question) in questions.indexed)
      AdvancedFamily(
        key: '${id}_q${index + 1}',
        title: title,
        topic: topic,
        level: level,
        bloom: question.bloom,
        creation: question.creation == null ? null : (_, _) => question.creation!,
        multiSelect: question.multiSelect == null ? null : (_, _) => question.multiSelect!,
        difficulty: level == StudyLevel.universite ? Difficulty.hard : Difficulty.medium,
        visualKind: VisualKind.image,
        count: 1,
        build: (_) => AdvancedItem(question.item.prompt, question.item.correct,
            question.item.wrong, question.item.explanation, visual: visual),
      ),
  ];
}

